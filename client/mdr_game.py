#!/usr/bin/env python3
"""
mdr_game.py -- turn a cartridge's BASIC loader into a SQL launch sequence.

The Microdrive release of Decathlon boots like this:

    CLEAR 24911
    RANDOMIZE USR 23955          setup
    LOAD *"m";d;"Day 1  0.0"CODE
    RANDOMIZE USR 32179          process the numbered block
    LOAD *"m";d;"Day 1  0.M"CODE
    RANDOMIZE USR 23999          launch

Every step of that is reproducible except the two LOADs, which are
Interface 1 shadow-ROM calls. We do those directly into dbo.z80_mem and
run the rest of the chain on the emulated CPU.
"""

import re
import sys


def _ident(name):
    return ''.join(c if c.isalnum() else '_' for c in name) or 'blk'


def _blob(f, comment):
    from sqlblob import emit_blob
    v = _ident(f['name'])
    return (
        f"\n/* {comment}\n"
        f"   {f['name']} -- {len(f['body'])} bytes at {f['addr']} "
        f"(0x{f['addr']:04X}-0x{f['addr'] + len(f['body']) - 1:04X}) */\n"
        + emit_blob(f'@{v}', f['body']) +
        f"EXEC dbo.z80_load_bin @data = @{v}, @addr = {f['addr']};\n"
        f"GO\n"
    )


def emit_game(files, path, day, detokenise):
    byname = {f['name']: f for f in files}
    basic = byname.get(day)
    if basic is None:
        sys.exit(f'no BASIC file named {day!r} '
                 f'(have: {", ".join(sorted(byname))})')

    blocks = [f for f in files
              if f.get('type') == 3 and f['name'].startswith(day)]
    mains = [f for f in blocks if f['name'].rstrip().endswith('M')]
    numbered = sorted((f for f in blocks if f not in mains),
                      key=lambda f: f['name'])
    if not mains:
        sys.exit(f'no "...M" CODE block found for {day!r}')
    main = mains[0]

    listing = ' '.join(detokenise(basic['body']))
    usrs = [int(n) for n in re.findall(r'RANDOMIZE USR VAL "(\d+)"', listing)]
    usrs += [int(n) for n in re.findall(r'RANDOMIZE USR (\d+)', listing)]
    if len(usrs) < 2:
        sys.exit(f'could not find the USR chain in {day!r}: found {usrs}')
    setup, entry = usrs[0], usrs[-1]

    m = re.search(r'CLEAR VAL "(\d+)"', listing) or re.search(r'CLEAR (\d+)', listing)
    ramtop = int(m.group(1)) if m else 24911

    chain = '\n'.join(
        f"       LOAD CODE -> {b['addr']} then RANDOMIZE USR {b['addr']}"
        for b in numbered)

    header = f"""/* =====================================================================
   05_game.sql -- GENERATED by mdr_extract.py --game "{day}"

   Launch sequence lifted from the cartridge's own BASIC loader:

       CLEAR {ramtop}
       RANDOMIZE USR {setup}            <- setup, emulated below, not called
{chain}
       LOAD CODE -> {main['addr']}
       RANDOMIZE USR {entry}            <- launches the game

   USR {setup} is skipped deliberately. It replaces SP with a stack planted
   below ERR_SP and RETs into the BASIC interpreter, which only makes
   sense with BASIC still running underneath. On a 48K machine its whole
   observable effect is ATTR_P = 0 and a cleared display, done here with
   two UPDATEs. Its OUT ($7FFD),$10 is a 128K ROM-paging write and a
   no-op on 48K -- our port decode ignores odd ports, so that already
   behaves correctly.
   ===================================================================== */
SET NOCOUNT ON;
GO

/* ---- prerequisite check ------------------------------------------
   This script needs the breakpoint support in z80_run. Without it
   z80_call cannot see the return address -- PC holds it for exactly one
   instruction -- and the machine reboots through 0x0000 instead, which
   looks like a hung loader rather than a stale deployment. Fail loudly
   here rather than spend three minutes producing a wrong answer.        */
IF NOT EXISTS (SELECT 1 FROM sys.parameters
                WHERE object_id = OBJECT_ID('dbo.z80_run') AND name = '@stop_pc')
BEGIN
    RAISERROR('dbo.z80_run has no @stop_pc parameter: 02_z80_core.sql is out of date. Reload it and 03_driver.sql, then retry.', 16, 1);
    SET NOEXEC ON;
END
GO
IF NOT EXISTS (SELECT 1 FROM sys.sql_modules
                WHERE object_id = OBJECT_ID('dbo.z80_call')
                  AND definition LIKE '%@stop_pc%')
BEGIN
    RAISERROR('dbo.z80_call does not use the breakpoint: 03_driver.sql is out of date. Reload it and retry.', 16, 1);
    SET NOEXEC ON;
END
GO
SELECT id, build, loaded_at,
       CASE id WHEN 1 THEN 'z80 core' WHEN 2 THEN 'driver' END AS component
FROM dbo.z80_build ORDER BY id;
GO

EXEC dbo.z80_boot;
GO

/* CLEAR {ramtop} : RAMTOP */
UPDATE dbo.z80_mem SET val = {ramtop} % 256 WHERE addr = 23730;
UPDATE dbo.z80_mem SET val = {ramtop} / 256 WHERE addr = 23731;

/* what USR {setup} would have left behind */
UPDATE dbo.z80_mem SET val = 0 WHERE addr BETWEEN 16384 AND 23295;
UPDATE dbo.z80_mem SET val = 0 WHERE addr IN (23693, 23695);   -- ATTR_P, ATTR_T
GO
"""

    out = [header,
           _blob(basic, 'BASIC program: holds the embedded loader in its REM')]
    for b in numbered:
        out.append(_blob(b, 'numbered CODE block'))
        out.append(f"EXEC dbo.z80_call @addr = {b['addr']}, @max_frames = 200;\nGO\n")
    out.append(_blob(main, 'main CODE block'))
    out.append(f"""
/* USR {entry} copies its own entry stub out of the top of the main block,
   restores a saved register set from the REM area and jumps in. It runs
   DI and sets IM 1 itself, so hand it control with interrupts off. */
EXEC dbo.z80_start_code @entry = {entry}, @ei = 0;
GO

EXEC dbo.z80_run_frames @frames = 250, @capture = 1;
GO

SET NOEXEC OFF;
GO
""")

    with open(path, 'w') as fh:
        fh.write(''.join(out))
    print(f'\nwrote {path}')
    print(f'  CLEAR {ramtop}; setup USR {setup} (skipped); '
          f'{len(numbered)} numbered block(s); entry USR {entry}')
    return {'setup': setup, 'entry': entry, 'ramtop': ramtop,
            'numbered': [b['addr'] for b in numbered], 'main': main['addr']}
